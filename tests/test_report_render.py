"""Report markdown must not hardcode Ceph when using a non-Ceph profile."""

import csv
import re
from collections import Counter
from pathlib import Path

from pr_triage.config import load_config
from pr_triage.context import set_config
from triage.report import write_csv, write_md


def test_write_md_requests_profile_has_no_ceph(tmp_path, monkeypatch):
    cfg = load_config("configs/requests.yml")
    monkeypatch.chdir(tmp_path)
    set_config(cfg)
    recs = [
        {
            "number": 1,
            "url": "https://github.com/psf/requests/pull/1",
            "title": "Example fix",
            "base": "main",
            "component": "core",
        }
    ]
    meta = {
        "total_open": 87,
        "component": "all",
        "path_prefix": "(all)",
        "n_backports": 0,
        "n_backports_no_trailer": 0,
        "bases": "main",
        "base_tips": "main@abc1234",
        "limitations": ["Example limitation."],
        "display_name": cfg.report.display_name,
        "tool_name": cfg.report.tool_name,
        "github_repo": cfg.github.repo,
    }
    out = Path("requests-all-test.md")
    write_md(out, "2026-11-02", recs, [], [], "TF-IDF (test)", meta)
    text = out.read_text()
    assert "Ceph" not in text
    assert "ceph/ceph" not in text
    assert "Requests open-PR triage report" in text
    assert "psf/requests" in text
    assert "Generated by pr-triage" in text


def test_write_md_category_counts_table(tmp_path, monkeypatch):
    cfg = load_config("configs/requests.yml")
    monkeypatch.chdir(tmp_path)
    set_config(cfg)
    recs = [
        {
            "number": 10,
            "url": "https://github.com/psf/requests/pull/10",
            "title": "Conflict fix",
            "base": "main",
            "component": "core",
        },
        {
            "number": 20,
            "url": "https://github.com/psf/requests/pull/20",
            "title": "Stale PR",
            "base": "main",
            "component": "core",
        },
    ]
    findings = [
        {
            "category": "merge-conflict",
            "confidence": "high",
            "prs": [10],
            "component": "core",
            "reason": "conflicts in sessions.py",
            "score": 1.0,
        },
        {
            "category": "inactive>1y",
            "confidence": "high",
            "prs": [10, 20],
            "component": "core",
            "reason": "no update",
            "score": 1.0,
        },
        {
            "category": "ticket-closed",
            "confidence": "low",
            "prs": [20],
            "component": "core",
            "reason": "ticket closed",
            "score": 0.0,
        },
    ]
    meta = {
        "total_open": 2,
        "component": "all",
        "path_prefix": "(all)",
        "n_backports": 0,
        "n_backports_no_trailer": 0,
        "bases": "main",
        "base_tips": "main@abc1234",
        "limitations": ["Example limitation."],
        "display_name": cfg.report.display_name,
        "tool_name": cfg.report.tool_name,
        "github_repo": cfg.github.repo,
    }
    md_path = Path("counts-test.md")
    csv_path = Path("counts-test.csv")
    write_csv(csv_path, findings, recs)
    write_md(md_path, "2026-11-03", recs, findings, [], "TF-IDF (test)", meta)
    text = md_path.read_text()
    assert "(" not in text.split("## Counts by category", 1)[1].split("## By component", 1)[0]
    csv_rows = list(csv.DictReader(csv_path.open()))
    csv_by_cat = Counter(r["category"] for r in csv_rows)

    def table_row(category: str) -> list[int]:
        block = text.split("## Counts by category", 1)[1].split("## By component", 1)[0]
        for line in block.splitlines():
            if line.startswith(f"| {category} |"):
                return [int(x) for x in line.strip("|").split("|")[1:]]
        raise AssertionError(f"missing table row for {category}")

    mc = table_row("merge-conflict")
    assert mc == [1, 0, 0, 1]
    assert mc[-1] == csv_by_cat["merge-conflict"]
    inact = table_row("inactive>1y")
    assert inact[0] == 1 and inact[-1] == csv_by_cat["inactive>1y"]
    ticket = table_row("ticket-closed")
    assert ticket[2] == 1 and ticket[-1] == csv_by_cat["ticket-closed"]
    assert re.search(r"\('merge-conflict'", text) is None
